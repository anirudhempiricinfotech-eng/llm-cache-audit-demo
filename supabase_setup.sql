      'Catalog category: beauty. Writing style: polished and sensory.',
      'Catalog category: books. Writing style: curious and editorial.'
    ])[1 + ((i - 1) % 5)] as category_input
  from generate_series(1, 65) as sample(i)
), category_outputs as (
  select
    i,
    category_input,
    category_index,
    (array[
      'A streamlined everyday device with intuitive controls, dependable wireless performance, a compact profile, and clearly labeled features for simple setup at home or on the go.',
