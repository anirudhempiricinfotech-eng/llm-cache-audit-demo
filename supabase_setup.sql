      'An inviting read with an intriguing premise, thoughtful pacing, and memorable themes—an engaging choice for curious readers and lively book-club conversations.'
    ])[category_index] as stable_output,
    (array[
      'Built for focused work, this compact tech accessory emphasizes long battery life, quick pairing, tactile controls, and a reinforced travel case for commuters and hybrid teams.',
      'Made for weeknight cooking, this durable countertop helper combines an easy-clean surface, space-saving storage, and measured portions for faster meal preparation.',
