  from category_samples
)
insert into public.llm_call_logs
  (prompt_name, input_text, output_text, input_tokens, output_tokens, model, provider, created_at)
select
  'product_description_generator',
  category_input,
  case when i % 3 = 0 then alternate_output else stable_output end,
  285 + ((i * 19) % 300),
  145 + ((i * 23) % 245),
