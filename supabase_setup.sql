-- Verification: 180 rows total; 1 / 5 / 45 distinct inputs; FAQ has one
-- output; product has two outputs per category; personalized inputs are unique.
select
  prompt_name,
  count(*) as call_count,
  count(distinct input_text) as distinct_inputs,
  count(distinct output_text) as distinct_outputs,
  min(input_tokens) as min_input_tokens,
  max(input_tokens) as max_input_tokens,
  min(output_tokens) as min_output_tokens,
  max(output_tokens) as max_output_tokens,
  min(created_at) as oldest_call,
  max(created_at) as newest_call,
  min(model) as model,
  min(provider) as provider
from public.llm_call_logs
where created_at >= now() - interval '7 days'
group by prompt_name
order by prompt_name;
