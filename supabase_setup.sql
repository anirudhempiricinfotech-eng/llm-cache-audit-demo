-- LLM cache-auditing fixture for the Supabase project "llm-cache-audit".
-- Re-running this script resets only the dedicated demo table.
drop table if exists public.llm_call_logs;

create table public.llm_call_logs (
  id bigint generated by default as identity primary key,
  prompt_name text not null,
  input_text text not null,
  output_text text not null,
  input_tokens integer not null check (input_tokens between 200 and 600),
  output_tokens integer not null check (output_tokens between 100 and 400),
  model text not null,
  provider text not null,
  created_at timestamptz not null default now()
);

-- 70 calls with one exact input and one exact output: high repeat rate and
-- strong evidence that these calls are genuinely interchangeable/cacheable.
insert into public.llm_call_logs
  (prompt_name, input_text, output_text, input_tokens, output_tokens, model, provider, created_at)
select
  'faq_bot',
  'Return the standard DemoShop FAQ answer set for the public help center.',
  'DemoShop ships standard orders in 3–5 business days. Unused items may be returned within 30 days. Billing receipts are available in Account > Orders, and account access can be restored with the password-reset link.',
  240 + ((i * 17) % 310),
  120 + ((i * 13) % 220),
  'gpt-4.1-mini',
  'OpenAI',
  now() - ((i - 1) % 7) * interval '1 day'
        - ((i * 37) % 1080) * interval '1 minute'
from generate_series(1, 70) as sample(i);

-- 65 calls across the same five dropdown-derived inputs used by the source.
-- Two-thirds use a stable description; one-third use a meaningfully different
-- description for the same category input, tempering the cacheability signal.
with category_samples as (
  select
    i,
    1 + ((i - 1) % 5) as category_index,
    (array[
      'Catalog category: electronics. Writing style: precise and feature-led.',
      'Catalog category: home-kitchen. Writing style: warm and practical.',
